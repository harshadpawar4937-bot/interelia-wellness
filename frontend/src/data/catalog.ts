/** SVG-style gradient placeholders as data URIs for product imagery */
function productGradient(seed: string, label: string): string {
  const hues: Record<string, [string, string]> = {
    red: ['#E52B40', '#ff7a88'],
    soft: ['#fef0f2', '#e52b40'],
    green: ['#1a7f4b', '#6bcf9a'],
    blue: ['#1a5f9e', '#6bb3e8'],
    amber: ['#c47a00', '#f0c060'],
    purple: ['#5b3a8c', '#a78bdb'],
    teal: ['#0d7377', '#5cc8c8'],
  }
  const [a, b] = hues[seed] ?? hues.red
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="600" height="600" viewBox="0 0 600 600">
    <defs><linearGradient id="g" x1="0%" y1="0%" x2="100%" y2="100%">
      <stop offset="0%" style="stop-color:${a}"/><stop offset="100%" style="stop-color:${b}"/>
    </linearGradient></defs>
    <rect width="600" height="600" fill="url(#g)"/>
    <circle cx="300" cy="260" r="90" fill="rgba(255,255,255,0.25)"/>
    <text x="300" y="480" text-anchor="middle" fill="white" font-family="system-ui" font-size="28" font-weight="600">${label}</text>
  </svg>`
  return `data:image/svg+xml,${encodeURIComponent(svg)}`
}

